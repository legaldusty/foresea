import { chromium, devices } from '@playwright/test';
import { io } from 'socket.io-client';
const base = process.env.BASE || 'http://localhost:5170';
const out = process.argv[2];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
const phone = await ctx.newPage();
const cmd = io(base, { auth: { role: 'command' } });
let last = null;
cmd.on('snapshot', (s) => { last = s; });
const send = (n, p) => new Promise((ok) => cmd.timeout(3000).emit(n, p, ok));
while (!last) await sleep(100);
await send('reset', { mode: 'tuesday' });
await phone.goto(`${base}/captain?v=ferry1`);
await phone.getByTestId('join').click();
await sleep(1200);
const route = last.vessels.find((v) => v.id === 'ferry1').route;
await send('dropZone', { kind: 'whale', lonlat: route[Math.floor(route.length * 0.4)] });
await sleep(400);
await send('publish', { draftId: last.drafts[0].id });
await sleep(1500);
await ctx.setOffline(true);
await send('clock', { paused: true });
await phone.waitForTimeout(25000);
const stale = await phone.getByTestId('stale').textContent().catch(() => null);
await phone.screenshot({ path: out });
console.log('stale line:', stale);
await ctx.setOffline(false);
await send('clock', { paused: false });
await browser.close();
process.exit(0);
